class Property {

  final String id;
  final String name;
  final String location;
  final String price;
  final String area;
  final String type;
  final String image;
  final String description;
  final List<String> facilities;


  Property({

    required this.id,
    required this.name,
    required this.location,
    required this.price,
    required this.area,
    required this.type,
    required this.image,
    required this.description,
    required this.facilities,

  });


}
